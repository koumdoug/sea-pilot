// Génère la variante PostgreSQL du schéma + sa migration initiale à partir de prisma/schema.prisma (source de vérité).
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { spawnSync } from "node:child_process";

const src = readFileSync("prisma/schema.prisma", "utf8");
if (!src.includes('provider = "sqlite"')) throw new Error("prisma/schema.prisma doit utiliser le provider sqlite");
const header = "// FICHIER GÉNÉRÉ par `npm run db:gen-pg` à partir de prisma/schema.prisma — ne pas modifier à la main.\n";
mkdirSync("prisma/postgres/migrations/0001_init", { recursive: true });
writeFileSync("prisma/postgres/schema.prisma", header + src.replace('provider = "sqlite"', 'provider = "postgresql"'));
const r = spawnSync("npx", ["prisma", "migrate", "diff", "--from-empty", "--to-schema-datamodel", "prisma/postgres/schema.prisma", "--script"], { encoding: "utf8", shell: true });
if (r.status !== 0) { console.error(r.stderr); process.exit(1); }
writeFileSync("prisma/postgres/migrations/0001_init/migration.sql", r.stdout);
writeFileSync("prisma/postgres/migrations/migration_lock.toml", '# Please do not edit this file manually\nprovider = "postgresql"\n');
console.log("Schéma et migration PostgreSQL générés dans prisma/postgres/");
